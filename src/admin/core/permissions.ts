export function requirePermission(...codes: PermissionCode[]) {
  return (req: Request, _res: Response, next: NextFunction) => {
    const ctx = getCtx(req);
    const hasAny = codes.some((code) =>
      typeof ctx.hasPermission === "function"
        ? ctx.hasPermission(code)
        : ctx.permissions?.has(code),
    );
    if (!hasAny) {
      return next(
        adminForbidden(
          "permission_denied",
          `Required permission: ${codes.join(" or ")}`,
          { required: codes },
        ),
      );
    }
    next();
  };
}

export function assertPermission(ctx: AdminContext, code: string): void {
  const has = typeof ctx.hasPermission === "function"
    ? ctx.hasPermission(code)
    : ctx.permissions?.has(code);
  if (!has) {
    throw adminForbidden("permission_denied", `Required permission: ${code}`, { required: [code] });
  }
}
